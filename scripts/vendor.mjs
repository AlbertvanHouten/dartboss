// Builds the two third-party files multi-device play needs into web/vendor, so nothing loads from
// a CDN: Trystero (Nostr signalling, bundled with its dependencies into one ES module) and the
// qrcode-generator script. Run after changing their versions in package.json:
//   npm run vendor
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

const OUT = new URL('../web/vendor/', import.meta.url);
const version = async name => JSON.parse(await readFile(new URL(`../node_modules/${name}/package.json`, import.meta.url), 'utf8')).version;
const header = async (name) => `/* ${name} ${await version(name)}, MIT licence. Generated by scripts/vendor.mjs; do not edit. */\n`;

await mkdir(OUT, { recursive: true });

await build({
  entryPoints: ['trystero/nostr'],
  outfile: new URL('trystero-nostr.mjs', OUT).pathname,
  bundle: true, format: 'esm', minify: true, platform: 'browser', target: 'es2020',
  banner: { js: (await header('trystero')).trim() },
  legalComments: 'none',
});

const qr = await readFile(new URL('../node_modules/qrcode-generator/dist/qrcode.js', import.meta.url), 'utf8');
await writeFile(new URL('qrcode.js', OUT), (await header('qrcode-generator')) + qr);
